//! Embeds every `assets/icons/*.png` into the binary, so the kiosk shows its food
//! artwork no matter which directory it is launched from.

use std::path::PathBuf;
use std::{env, fs};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let dir = manifest.join("assets").join("icons");
    println!("cargo:rerun-if-changed=assets/icons");

    let mut entries: Vec<(String, PathBuf)> = fs::read_dir(&dir)
        .map(|read| {
            read.filter_map(|entry| entry.ok().map(|e| e.path()))
                .filter(|path| path.extension().is_some_and(|ext| ext == "png"))
                .filter_map(|path| Some((path.file_stem()?.to_str()?.to_owned(), path)))
                .collect()
        })
        .unwrap_or_default();
    entries.sort();

    let lines: String = entries
        .iter()
        .map(|(name, path)| format!("    ({name:?}, include_bytes!({:?})),\n", path.display().to_string()))
        .collect();
    let code = format!(
        "/// Generated by build.rs from `assets/icons`: (code points, PNG bytes).\n\
         pub static EMBEDDED_ICONS: &[(&str, &[u8])] = &[\n{lines}];\n"
    );
    let out = PathBuf::from(env::var("OUT_DIR").expect("set by cargo")).join("embedded_icons.rs");
    fs::write(out, code).expect("write embedded icon table");
}
